"""BrowserRaf text renderer hardening tests (host C fixture only).

This suite does not claim browser DOM/JavaScript/TLS or ChatGPT compatibility.
No network or credentials. The generated browser runtime has no stdlib dependencies.
"""
from __future__ import annotations

from pathlib import Path
import os
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]

C_SOURCE = r"""
#include "BrowserRaf/internal/br_html.h"
static u8 out[2048];

static int contains(const char *needle) {
    u32 n=0;
    while(needle[n])n++;
    for(u32 i=0;i+n<2048u;i++){
        u32 j=0;
        while(j<n&&out[i+j]==(u8)needle[j])j++;
        if(j==n)return 1;
    }
    return 0;
}
static int has_byte(u8 c, u32 n) {
    for(u32 i=0;i<n;i++)if(out[i]==c)return 1;
    return 0;
}
int main(void){
    static const char page[]=
      "<!doctype html><html><head><style>.hide{display:none}CSS_HIDDEN"
      "</style><script defer src='/x.js'>JS_HIDDEN</script></head>"
      "<body><h1 class='hero'>SAFE_HEADING</h1>"
      "<ScRiPt type='module'>INJECT_TEXT</sCrIpT >"
      "<STYLE media='all'>INJECT_CSS</style>"
      "<p>VISIBLE&#27;[2J &amp; STABLE</p></body></html>";
    for(u32 i=0;i<sizeof(out);i++)out[i]=0xA5u;
    if(HTML_RENDER((const u8*)page,(u32)sizeof(page)-1u,out,0u)!=0u)return 1;
    for(u32 i=0;i<sizeof(out);i++)if(out[i]!=0xA5u)return 2;
    if(HTML_RENDER((const u8*)page,(u32)sizeof(page)-1u,0,0u)!=0u)return 3;
    if(HTML_RENDER(0,1u,out,10u)!=0u||out[0]!=0u)return 4;

    for(u32 i=0;i<sizeof(out);i++)out[i]=0xA5u;
    if(HTML_RENDER((const u8*)page,(u32)sizeof(page)-1u,out,1u)!=0u)return 5;
    if(out[0]!=0u||out[1]!=0xA5u)return 6;
    for(u32 i=0;i<sizeof(out);i++)out[i]=0u;
    u32 n=HTML_RENDER((const u8*)page,(u32)sizeof(page)-1u,out,(u32)sizeof(out));
    if(!n||!contains("SAFE_HEADING")||!contains("VISIBLE")||!contains("STABLE"))return 7;
    if(contains("INJECT_TEXT")||contains("INJECT_CSS")||
       contains("JS_HIDDEN")||contains("CSS_HIDDEN"))return 8;
    /* ANSI generated by renderer itself is separate from raw ESC injection. */
    if(contains("\x1b[2J")||has_byte(7u,n))return 9;

    static const char control[]="<p>OK\x1b[2J\x07" "DONE</p>";
    for(u32 i=0;i<sizeof(out);i++)out[i]=0u;
    n=HTML_RENDER((const u8*)control,(u32)sizeof(control)-1u,out,sizeof(out));
    if(!n||contains("\x1b[2J")||has_byte(7u,n)||!contains("DONE"))return 10;

    static const char unclosed[]="SAFE<script src='x'>NO_LEAK";
    for(u32 i=0;i<sizeof(out);i++)out[i]=0u;
    HTML_RENDER((const u8*)unclosed,sizeof(unclosed)-1u,out,sizeof(out));
    if(!contains("SAFE")||contains("NO_LEAK"))return 11;
    return 0;
}
"""

class BrowserHtmlSafety(unittest.TestCase):
    def test_host_native_render_boundaries(self) -> None:
        compiler = shutil.which(os.environ.get("CC", "cc"))
        if compiler is None:
            self.skipTest("host compiler absent; cannot claim native test PASS")
        with tempfile.TemporaryDirectory(prefix="br_html_safety_") as directory:
            src = Path(directory) / "render.c"
            elf = Path(directory) / "render"
            src.write_text(C_SOURCE, encoding="utf-8")
            build = subprocess.run(
                [compiler, "-std=c11", "-O0", "-fno-builtin", "-Wall",
                 "-Wextra", "-I", str(ROOT), str(src), "-o", str(elf)],
                capture_output=True, text=True, timeout=25,
            )
            self.assertEqual(build.returncode, 0, build.stdout + build.stderr)
            run = subprocess.run([str(elf)], capture_output=True, text=True, timeout=10)
            self.assertEqual(run.returncode, 0, f"native return={run.returncode}, {run.stdout} {run.stderr}")

if __name__ == "__main__":
    unittest.main()
